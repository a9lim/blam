def body_cost(M):
    R = ('L','s',M); wt = rd.weight(R); return wt[1]-2+4*max(wt[2]-1,0)
def positions(t, path=(), bound=()):
    yield path, t, bound
    if t[0]=='L': yield from positions(t[2], path+(0,), bound+(t[1],))
    elif t[0]=='A':
        yield from positions(t[1], path+(0,), bound); yield from positions(t[2], path+(1,), bound)
def replace(t, path, new):
    if not path: return new
    if t[0]=='L': return ('L', t[1], replace(t[2], path[1:], new))
    if path[0]==0: return ('A', replace(t[1], path[1:], new), t[2])
    return ('A', t[1], replace(t[2], path[1:], new))
def handler_binders(M, path):
    """names x bound above path by a lambda that is the direct argument of s."""
    out=[]; t=M
    for i,step in enumerate(path):
        if t[0]=='A' and step==1 and t[1]==('V','s') and t[2][0]=='L' and i+1<len(path):
            out.append(t[2][1])
        t = t[2] if t[0]=='L' else (t[1] if step==0 else t[2])
    return out
