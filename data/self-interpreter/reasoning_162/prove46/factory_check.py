#!/usr/bin/env python3
"""Fixed role-sharing identities and exact source prices. No term search."""
import sys
sys.dont_write_bytecode = True
from pathlib import Path
import json

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "tools" / "self-interpreter"))
import blcc
import lc

def parse(src, frame):
    p = blcc.P(src)
    t = blcc.p_lc(p)
    p.ws()
    assert p.i == len(p.t)
    return blcc.to_db(t, frame)

def normal_step(t):
    if t[0] == "V":
        return None
    if t[0] == "L":
        u = normal_step(t[1])
        return None if u is None else ("L", u)
    if t[1][0] == "L":
        return lc.beta(t[1], t[2])
    u = normal_step(t[1])
    if u is not None:
        return ("A", u, t[2])
    u = normal_step(t[2])
    return None if u is None else ("A", t[1], u)

def steps_to(t, expected):
    for steps in range(100):
        if t == expected:
            return steps
        u = normal_step(t)
        assert u is not None, (t, expected)
        t = u
    raise AssertionError("fixed identity exceeded its limit")

def lean(t):
    if t[0] == "V":
        return f"(.var {t[1]})"
    if t[0] == "L":
        return f"(.lam {lean(t[1])})"
    return f"(.app {lean(t[1])} {lean(t[2])})"

def weight(t, d=0):
    if t[0] == "V":
        return 4*d if t[1] == d+1 else t[1]+2
    if t[0] == "L":
        return 2+weight(t[1], d+1)
    return 2+weight(t[1], d)+weight(t[2], d)

factory = r"\x. x (\q.c)"
arm = r"\u.s (\q.c) (s s u)"
base_src = rf"\s.s (\a.a) ({arm}) j"
expanded_src = rf"\s.s (\a.(\b.b) a) ({arm}) j"
shared_src = rf"\s.((\h.s (h (\a\b.b)) (\u.s (h (\a.a)) (s s u))) ({factory})) j"
base = parse(base_src, ("c", "j"))
expanded = parse(expanded_src, ("c", "j"))
shared = parse(shared_src, ("c", "j"))
I = ("L", ("V", 0))
H = parse(factory, ("c",))
Kc = parse(r"\q.c", ("c",))
facts = [
    ("factory_false", ("A", H, lc.FALSE), I),
    ("factory_ident", ("A", H, I), Kc),
    ("factory_self", ("A", H, H), ("V", 0)),
    ("expanded_selector_reader", expanded, base),
    ("shared_factory_reader", shared, base),
]
out = [
    "/- Five fixed beta equalities and exact prices, generated by factory_check.py. -/",
    "import Reader138", "import ShallowFacts", "",
    "namespace Blc.Round3Prove46Facts", "open Term SelfintWireCost Round3Reader138",
    "set_option maxRecDepth 10000", "set_option maxHeartbeats 1000000", "",
]
record = []
for name, t, u in facts:
    steps = steps_to(t, u)
    out.append(f"theorem {name} : Betas {lean(t)} {lean(u)} :=")
    out.append(f"  Round3Floor.normalSteps_sound (by decide : Round3Floor.normalSteps {steps} {lean(t)} = some {lean(u)})")
    out.append("")
    record.append(dict(name=name, steps=steps))
for name, t, want in [("reference", base, 46), ("expanded_selector", expanded, 52), ("shared_factory", shared, 75)]:
    assert weight(t) == want
    out.append(f"theorem {name}_weight : cost {lean(t)} + 4 * depth {lean(t)} = {want} := by decide")
    record.append(dict(name=name, weight=want, wire=lc.size(t)))
for name, src, want in [("factory", factory, 13), ("arm", arm, 28), ("expanded_identity", r"\a.(\b.b) a", 10)]:
    t = parse(src, ("s", "c"))
    assert lc.size(t) == want
    out.append(f"theorem {name}_wire : wire {lean(t)} = {want} := by decide")
out += ["", "end Blc.Round3Prove46Facts", ""]
(HERE / "ReaderFacts.lean").write_text("\n".join(out))
(HERE / "factory-checks.json").write_text(json.dumps(record, indent=2) + "\n")
(HERE / "shared-factory-reader.txt").write_text(shared_src + "\n")
print(json.dumps(record, sort_keys=True))
