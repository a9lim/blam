#!/usr/bin/env python3
"""Regenerate the compact Lean certificate for the 4,186,155,666-bit halter.

This untrusted, bounded DAG normalizer shares repeated subtrees and emits
ordinary Lean proofs for every scope, size, normality, shift, substitution,
and beta-reduction edge. Lean checks the generated certificate independently;
the generator's arithmetic and evaluator are not axioms or trusted code.

The default output is lean/Blc/BB35Large.lean in this script's repository,
independent of the current directory. --check compares exact UTF-8 bytes and
never rewrites the output. --output permits checking a separate copy.

The reported contraction count counts distinct memoized operations, not the
normal-order machine's clock, and must not be used in speed-prior bounds.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUTPUT = ROOT / "lean/Blc/BB35Large.lean"
MAX_NODES = 10_000
MAX_CONTRACTIONS = 10_000
BITS = "01000101101010000001110011100110110"
EXPECTED_SIZE = 4_186_155_666


def require(condition, message):
    if not condition:
        raise ValueError(message)


sys.setrecursionlimit(20000)
nodes = []
table = {}
normal = []
size = []
free = []
events = []
shift_m = {}
sub_m = {}
weak_m = {}
reduce_m = {}
contractions = 0


def mk(tag, *x):
    key = (tag, *x)
    if key in table:
        return table[key]
    require(len(nodes) < MAX_NODES, "DAG node limit exceeded")
    i = len(nodes)
    nodes.append(key)
    table[key] = i
    if tag == "v":
        free.append(x[0] + 1)
        size.append(x[0] + 2)
        normal.append(True)
    elif tag == "l":
        free.append(max(0, free[x[0]] - 1))
        size.append(2 + size[x[0]])
        normal.append(normal[x[0]])
    else:
        free.append(max(free[y] for y in x))
        size.append(2 + sum(size[y] for y in x))
        normal.append(nodes[x[0]][0] != "l" and all(normal[y] for y in x))
    return i


v = lambda n: mk("v", n)
l = lambda b: mk("l", b)
a = lambda f, x: mk("a", f, x)


def shift(t, d, c=0):
    key = (t, d, c)
    if key in shift_m:
        return shift_m[key][0]
    z = nodes[t]
    if free[t] <= c:
        r = t
    elif z[0] == "v":
        r = v(z[1] + d if z[1] >= c else z[1])
    elif z[0] == "l":
        r = l(shift(z[1], d, c + 1))
    else:
        r = a(shift(z[1], d, c), shift(z[2], d, c))
    name = f"shift{len(shift_m)}"
    shift_m[key] = (r, name)
    events.append(("shift", key, r, name))
    return r


def sub(t, s, j=0):
    key = (t, s, j)
    if key in sub_m:
        return sub_m[key][0]
    z = nodes[t]
    if free[t] <= j:
        r = t
    elif z[0] == "v":
        r = s if z[1] == j else v(z[1] - 1 if z[1] > j else z[1])
    elif z[0] == "l":
        r = l(sub(z[1], shift(s, 1), j + 1))
    else:
        r = a(sub(z[1], s, j), sub(z[2], s, j))
    name = f"sub{len(sub_m)}"
    sub_m[key] = (r, name)
    events.append(("sub", key, r, name))
    return r


def weak(t):
    global contractions
    if t in weak_m:
        return weak_m[t][0]
    z = nodes[t]
    if z[0] != "a":
        r = t
    else:
        f = weak(z[1])
        w = nodes[f]
        if w[0] != "l":
            r = a(f, z[2])
        else:
            contractions += 1
            require(
                contractions < MAX_CONTRACTIONS, "memoized contraction limit exceeded"
            )
            r = weak(sub(w[1], z[2]))
    name = f"weak{t}"
    weak_m[t] = (r, name)
    events.append(("weak", t, r, name))
    return r


def reduce(t):
    if t in reduce_m:
        return reduce_m[t][0]
    if normal[t]:
        r = t
    else:
        w = weak(t)
        z = nodes[w]
        if z[0] == "v":
            r = w
        elif z[0] == "l":
            r = l(reduce(z[1]))
        else:
            r = a(reduce(z[1]), reduce(z[2]))
    name = f"reduce{t}"
    reduce_m[t] = (r, name)
    events.append(("reduce", t, r, name))
    return r


def parse(bits, i=0):
    if bits[i] == "1":
        j = i
        while bits[j] == "1":
            j += 1
        return v(j - i - 1), j + 1
    if bits[i + 1] == "0":
        b, j = parse(bits, i + 2)
        return l(b), j
    f, j = parse(bits, i + 2)
    x, k = parse(bits, j)
    return a(f, x), k


T, end = parse(BITS)
require(end == len(BITS), "unconsumed BLC input")
R = reduce(T)
require(
    size[R] == EXPECTED_SIZE and free[R] == 0 and normal[R],
    "normal-form size, closedness, or normality invariant changed",
)
# Every operation is emitted as a compositional theorem; no native_decide
# or giant traversal appears in the trusted proof.
lines = [
    """/-
GENERATED by tools/certificates/bb35_large.py; do not edit this file by hand.
Regenerate: python tools/certificates/bb35_large.py
Check byte identity: python tools/certificates/bb35_large.py --check

A compact kernel certificate for the 35-bit halter
  01000101101010000001110011100110110 = (λx.x x x) A,
  A x y = x (x (y x)).
Its normal form has exactly 4,186,155,666 BLC bits.

The finite DAG below shares repeated subtrees. Every DAG node has a scope
and wire-length proof, and every normal node has a syntactic normality
proof. The evaluation certificate checks every shift, substitution, and
β-reduction compositionally. Consequently no 4 GB wire string or expanded
normal-form tree is constructed, and no evaluator is added to the trusted
base. The generator is untrusted; Lean checks all edges with ordinary
kernel reduction and the project's existing β-calculus theorems.
-/
import Blc.Confluence
import Blc.Wire

namespace Blc.BB35Large
open Term

private theorem sizeLam {b : Term} {n : Nat}
    (h : (blcCode b).length = n) : (blcCode (.lam b)).length = n + 2 := by
  simp only [blcCode, List.length_cons, h]

private theorem sizeApp {f a : Term} {m n : Nat}
    (hf : (blcCode f).length = m) (ha : (blcCode a).length = n) :
    (blcCode (.app f a)).length = m + n + 2 := by
  simp only [blcCode, List.length_cons, List.length_append, hf, ha]

private theorem appCongr {f f' a a' : Term} (hf : f = f') (ha : a = a') :
    Term.app f a = Term.app f' a' := by
  cases hf
  cases ha
  rfl

private theorem checkedBeta {b a u : Term} (h : substDec 0 a b = u) :
    Beta (.app (.lam b) a) u := by
  have hb := Beta.beta b a
  change Beta (.app (.lam b) a) (substDec 0 a b) at hb
  rw [h] at hb
  exact hb
"""
]
for i, z in enumerate(nodes):
    if z[0] == "v":
        ctor = f".var {z[1]}"
        sc = "by decide"
        sz = "by decide"
        nf = "by trivial"
    elif z[0] == "l":
        b = z[1]
        ctor = f".lam d{b}"
        sc = f"freeUnder_mono (by decide) scope{b}"
        sz = f"sizeLam size{b}"
        nf = f"normal{b}"
    else:
        f, b = z[1:]
        ctor = f".app d{f} d{b}"
        sc = f"⟨freeUnder_mono (by decide) scope{f}, freeUnder_mono (by decide) scope{b}⟩"
        sz = f"sizeApp size{f} size{b}"
        nf = f"⟨by trivial, normal{f}, normal{b}⟩"
    lines.append(f"private def d{i} : Term := {ctor}")
    lines.append(f"private theorem scope{i} : FreeUnder {free[i]} d{i} := {sc}")
    lines.append(f"private theorem size{i} : (blcCode d{i}).length = {size[i]} := {sz}")
    if normal[i]:
        lines.append(f"private theorem normal{i} : NFt d{i} := {nf}")
    lines.append("")

for kind, key, r, name in events:
    if kind == "shift":
        t, d, c = key
        z = nodes[t]
        goal = f"shift {d} {c} d{t} = d{r}"
        if free[t] <= c:
            pr = f"shift_of_freeUnder {d} d{t} {c} {free[t]} scope{t} (by decide)"
        elif z[0] == "v":
            pr = "by rfl"
        elif z[0] == "l":
            pr = f"congrArg Term.lam {shift_m[(z[1], d, c + 1)][1]}"
        else:
            pr = f"appCongr {shift_m[(z[1], d, c)][1]} {shift_m[(z[2], d, c)][1]}"
    elif kind == "sub":
        t, s, j = key
        z = nodes[t]
        goal = f"substDec {j} d{s} d{t} = d{r}"
        if free[t] <= j:
            pr = f"substDec_of_freeUnder d{t} {j} d{s} (freeUnder_mono (by decide) scope{t})"
        elif z[0] == "v":
            pr = "by rfl"
        elif z[0] == "l":
            shifted, shiftname = shift_m[(s, 1, 0)]
            child = sub_m[(z[1], shifted, j + 1)][1]
            pr = f"""by
  change Term.lam (substDec {j + 1} (shift 1 0 d{s}) d{z[1]}) = _
  rw [{shiftname}]
  exact congrArg Term.lam {child}"""
        else:
            pr = f"appCongr {sub_m[(z[1], s, j)][1]} {sub_m[(z[2], s, j)][1]}"
    elif kind == "weak":
        t = key
        z = nodes[t]
        goal = f"Betas d{t} d{r}"
        if z[0] != "a":
            pr = f"Betas.refl d{t}"
        else:
            f, fn = weak_m[z[1]]
            w = nodes[f]
            start = f"betas_appL d{z[2]} {fn}"
            if w[0] != "l":
                pr = start
            else:
                subresult, sn = sub_m[(w[1], z[2], 0)]
                pr = f"betas_trans ({start}) (Betas.head (checkedBeta {sn}) {weak_m[subresult][1]})"
    else:
        t = key
        goal = f"Betas d{t} d{r}"
        if normal[t]:
            pr = f"Betas.refl d{t}"
        else:
            w, wn = weak_m[t]
            z = nodes[w]
            if z[0] == "v":
                pr = wn
            elif z[0] == "l":
                pr = f"betas_trans {wn} (betas_lam {reduce_m[z[1]][1]})"
            else:
                f, fn = reduce_m[z[1]]
                arg, an = reduce_m[z[2]]
                pr = f"betas_trans {wn} (betas_trans (betas_appL d{z[2]} {fn}) (betas_appR d{f} {an}))"
    lines.append(f"private theorem {name} : {goal} := {pr}\n")
lines.append(f"""
/-- The exact census input. -/
def target : Term := d{T}
/-- A finite, shared representation of its enormous normal form. -/
def normalForm : Term := d{R}

theorem wire : blcCode target =
    [{", ".join("true" if b == "1" else "false" for b in BITS)}] := by decide

theorem closed : Closed target := scope{T}
theorem output_closed : Closed normalForm := scope{R}

theorem normalization : Betas target normalForm := {reduce_m[T][1]}

theorem normal : NormalForm normalForm := fun _ h => nft_no_beta normal{R} h

theorem hasNormalForm : HasNormalForm target := ⟨normalForm, normalization, normal⟩

theorem normalForm_size : (blcCode normalForm).length = 4186155666 := size{R}

/-- Every β-normal form of this exact input has this exact wire size. -/
theorem exact_normalForm_size {{u : Term}} (hu : Betas target u)
    (hn : NormalForm u) : (blcCode u).length = 4186155666 := by
  have heq := normalForm_unique hu normalization hn normal
  rw [heq]
  exact normalForm_size

end Blc.BB35Large
""")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="require byte-identical generated output without rewriting it",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="output/check path (default: repository lean/Blc/BB35Large.lean)",
    )
    args = parser.parse_args()
    generated = "\n".join(lines).encode("utf-8")
    if args.check:
        try:
            existing = args.output.read_bytes()
        except OSError as exc:
            parser.exit(1, f"bb35-large: cannot check {args.output}: {exc}\n")
        if existing != generated:
            parser.exit(1, f"bb35-large: generated bytes differ: {args.output}\n")
        action = "checked"
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(generated)
        action = "wrote"
    print(
        f"bb35-large: {action} {args.output}; {len(nodes)} DAG nodes, "
        f"{len(shift_m)} shifts, {len(sub_m)} substitutions, "
        f"{contractions} distinct memoized contractions, "
        f"{size[R]:,} normal-form bits"
    )


if __name__ == "__main__":
    main()
