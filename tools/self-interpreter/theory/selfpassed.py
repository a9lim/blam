#!/usr/bin/env python3
"""One hand-derived interpreter with a self-passed recursive context.

No candidate enumeration. The fixed equations implement the ordinary open
parser recurrence; the battery and divergent-source probes check this one
191-bit source. Its all-source correctness derivation is handwritten.
"""
from pathlib import Path
import json
import sys
import time

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MACHINES = ROOT / "data/self-interpreter/machines"
RESULTS = ROOT / "data/self-interpreter/theory"
sys.path.insert(0, str(ROOT / "tools/self-interpreter"))
import battery as b
import lc
from remainder import check_clause, counts


ABS = r"(\e\a.f (\b\r.b a (r e)))"
APP = r"(\e.f e (g e))"
CONTINUATION = rf"\t\d\c\f.t (c {ABS}) (\v.v d (\g.c {APP}) d)"
NEXT = rf"\t\u\c\d.u d (\f.t (c {ABS}) (\v.v d (\g.c {APP}) d)) d"
CONTEXT = rf"\b\r.b (r ({NEXT})) (\c\d.c r (r r d))"
SOURCE = rf"\c\s.(\d.s d c d) ({CONTEXT})"


def apps(function, *arguments):
    for argument in arguments:
        function = ("A", function, argument)
    return function


def instantiate(source, *arguments):
    term = b.compile_lam(source)
    for argument in arguments:
        term = lc.beta(term, argument)
    return term


def fixed_clauses(term, context, next_term):
    continuation, tail, stream, first, second, remainder = [("V", i) for i in range(6)]

    def parse(callback, source):
        return apps(source, context, callback, context)

    abs_value = instantiate(r"\f." + ABS, first)
    app_value = instantiate(r"\f\g." + APP, first, second)
    abs_callback = instantiate(CONTINUATION, lc.TRUE, context, continuation)
    app_callback = instantiate(CONTINUATION, lc.FALSE, context, continuation)
    second_callback = instantiate(r"\c\f\g.c " + APP, continuation, first)
    return {
        "unfold": check_clause(apps(term, continuation, tail), parse(continuation, tail), 3),
        "variable": check_clause(parse(continuation, lc.pair(lc.FALSE, tail)),
                                 apps(continuation, tail, apps(tail, tail, context)), 7),
        "zero": check_clause(parse(continuation, lc.pair(lc.TRUE, tail)),
                             apps(tail, next_term, continuation, context), 5),
        "abstraction_parse": check_clause(apps(lc.pair(lc.TRUE, stream), next_term,
                                                continuation, context),
                                            parse(abs_callback, stream), 5),
        "application_parse": check_clause(apps(lc.pair(lc.FALSE, stream), next_term,
                                                continuation, context),
                                            parse(app_callback, stream), 5),
        "abstraction_return": check_clause(apps(abs_callback, first, remainder),
                                            apps(continuation, abs_value, remainder), 3),
        "application_second_parse": check_clause(apps(app_callback, first, remainder),
                                                  parse(second_callback, remainder), 4),
        "application_return": check_clause(apps(second_callback, second, remainder),
                                            apps(continuation, app_value, remainder), 1),
    }


def divergent_suffix_probe(term, source):
    source_term = b.compile_lam(source)
    tail_selector = b.compile_lam(r"\value\rest.rest")
    probe = ("L", apps(b.shift(term, 1), tail_selector,
                       b.bitlist(b.enc(source_term), ("V", 0))))
    assert b.normalize(b.enc(probe), 1 << 16) == "0010"


def main():
    start = time.monotonic()
    term = b.compile_lam(SOURCE)
    context = b.compile_lam(CONTEXT)
    next_term = b.compile_lam(NEXT)
    bits = b.enc(term)
    assert len(bits) == 191
    clauses = fixed_clauses(term, context, next_term)
    lambdas, applications, tax = counts(term)
    assert 2 * lambdas + 4 * applications + 2 + tax == len(bits)
    (MACHINES / "int191_selfpassed.lam").write_text(
        "-- Self-passed recursive context; generated by selfpassed.py.\n"
        "-- E C (<M> ++ N) =beta C (\\z.M) N for closed M.\n"
        + SOURCE + "\n"
    )
    (MACHINES / "int191_selfpassed.blc").write_text(bits + "\n")
    ok, skipped, failures = b.check(term, max_bits=18, threads=2)
    divergent_sources = {
        "omega": r"(\x.x x) (\x.x x)",
        "lambda_omega": r"\a.(\x.x x) (\x.x x)",
    }
    for source in divergent_sources.values():
        divergent_suffix_probe(term, source)
    result = {
        "search_performed": False,
        "name": "int191_selfpassed",
        "bits": len(bits),
        "source_counts": {"lambdas": lambdas, "applications": applications, "index_tax": tax},
        "context_bits": lc.size(context),
        "next_bits": lc.size(next_term),
        "adapter_and_application_bits": len(bits) - lc.size(context),
        "symbolic_head_clause_steps": clauses,
        "battery": {"ok": ok, "skipped": skipped, "failures": failures},
        "divergent_source_suffix": dict.fromkeys(divergent_sources, True),
        "proof_status": "handwritten recurrence derivation; no separate Lean proof",
        "elapsed_seconds": round(time.monotonic() - start, 3),
    }
    assert ok == 667 and skipped == 1 and not failures, result
    (RESULTS / "selfpassed.json").write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
