#!/usr/bin/env python3
"""A continuation-free parser using an applicative metadata box; no search.

The box tag carries the unconsumed source. Application combines closure
payloads pointwise and retains the right box's tag. The construction is a
complete 303-bit interpreter, not a record-sized candidate.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import json
import sys
import time

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "tools/self-interpreter"))
import battery as b


K = r"(\u\w.u)"
F = r"(\u\w.w)"
GENERATOR = r"(\g\n\u\y\x\h.h (\r.r g n) (\e.x e (y e)))"
BOX = rf"(\v\n\h.h (\r.r {GENERATOR} n) v)"
ABS_HANDLER = r"(\tag\body\h.h tag (\env\arg.body (\b\r.b arg (r env))))"
NEXT = rf"""(\bit\rest.
  (\v.v (bit {ABS_HANDLER} (p (v {K} bit)))) (p rest))"""
BODY = rf"""(\next\list.
  list (\bit.bit (\unused\r.r next) {BOX}) (list list list))
  {NEXT}"""
PARSER = rf"((\x.x x) (\x.(\p.{BODY}) (x x)))"
SOURCE = rf"""(\p\cont\list.
  p list (\tag\value.cont value (tag {F}))) {PARSER}"""


def normalize(source):
    term = b.compile_lam(source)
    result = b.normalize(b.enc(term), 1 << 16)
    assert result is not None, source
    return result


def divergent_suffix_probe(interpreter, source):
    term = b.compile_lam(source)
    probe = ("L", ("A", ("A", b.shift(interpreter, 1), b.FALSE),
                   b.bitlist(b.enc(term), ("V", 0))))
    result = b.normalize(b.enc(probe), 1 << 18)
    assert result == "0010", (source, result)


def main():
    start = time.monotonic()
    sizes = {
        name: len(b.enc(b.compile_lam(source)))
        for name, source in [
            ("generator", GENERATOR),
            ("box_constructor", BOX),
            ("abs_handler", ABS_HANDLER),
            ("interpreter", SOURCE),
        ]
    }
    assert sizes == {
        "generator": 62, "box_constructor": 90,
        "abs_handler": 51, "interpreter": 303,
    }, sizes
    cases = [
        ("payload_projection", rf"\n\x.({BOX} x n) {F}", r"\n\x.x"),
        ("remainder_projection", rf"\n\x.({BOX} x n) {K} {F}", r"\n\x.n"),
        ("application_keeps_right_remainder",
         rf"\m\n\x\y.({BOX} x m) ({BOX} y n)",
         rf"\m\n\x\y.{BOX} (\e.x e (y e)) n"),
        ("abstraction_keeps_remainder",
         rf"\n\x.({BOX} x n) {ABS_HANDLER}",
         rf"\n\x.{BOX} (\env\arg.x (\b\r.b arg (r env))) n"),
        ("identity_closure_is_pointwise_idempotent",
         rf"\e.{F} e ({F} e)", F),
        ("parser_metadata_box_is_idempotent",
         rf"\p.({BOX} {F} p) ({BOX} {F} p)",
         rf"\p.{BOX} {F} p"),
        ("parser_metadata_box_projects_parser",
         rf"\p.({BOX} {F} p) {K} {F}", r"\p.p"),
    ]
    sources = [source for _, left, right in cases for source in (left, right)]
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(normalize, sources))
    for index, (name, _, _) in enumerate(cases):
        assert results[2 * index] == results[2 * index + 1], name

    interpreter = b.compile_lam(SOURCE)
    wire = b.enc(interpreter)
    machines = ROOT / "data/self-interpreter/machines"
    name = "int303_metadata"
    (machines / f"{name}.lam").write_text(
        "-- Applicative remainder metadata; generated by metadata_parser.py.\n"
        "-- E C (<M> ++ N) =beta C (\\z.M) N for closed M.\n"
        + SOURCE.strip() + "\n"
    )
    (machines / f"{name}.blc").write_text(wire + "\n")
    ok, skipped, failures = b.check(interpreter, max_bits=18, threads=2)
    assert (ok, skipped, len(failures)) == (667, 1, 0), failures
    divergent_sources = {
        "omega": r"(\x.x x) (\x.x x)",
        "lambda_omega": r"\a.(\x.x x) (\x.x x)",
    }
    with ThreadPoolExecutor(max_workers=2) as pool:
        list(pool.map(lambda source: divergent_suffix_probe(interpreter, source),
                      divergent_sources.values()))
    report = {
        "search_performed": False,
        "sizes": sizes,
        "rigid_equations": [name for name, _, _ in cases],
        "battery": {"ok": ok, "skipped": skipped, "failures": failures},
        "divergent_source_suffixes": list(divergent_sources),
        "elapsed_seconds": round(time.monotonic() - start, 3),
    }
    path = ROOT / "data/self-interpreter/theory/metadata_parser.json"
    path.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
