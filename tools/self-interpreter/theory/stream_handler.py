#!/usr/bin/env python3
"""Two hand-derived Scott-handler recursion arrangements; no search.

The ordinary parser is P c s = s (H H c). Every recursive entry eliminates
its Scott stream before invoking the shared recursive handler. The second
term shares H H inside its generator, reducing 206 bits to 196.
"""
from pathlib import Path
import json
import sys
import time

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
MACHINES = ROOT / "data/self-interpreter/machines"
RESULTS = ROOT / "data/self-interpreter/theory"
sys.path.insert(0, str(ROOT / "tools/self-interpreter"))
import battery as b


ABS = r"(\args\arg.exp (\zx\zy.zx arg (zy args)))"
APP = r"(\args.exp args (exp2 args))"

DIRECT = rf"""
(\h\cont\list.list (h h cont))
(\h\cont\bit0\list1.
  bit0
    (list1
      (\bit1\list2.list2
        (h h
          (\exp.bit1
            (cont {ABS})
            (\list3.list3 (h h (\exp2.cont {APP})))))))
    (cont list1 (list1 list1 list1)))
"""

SHARED = rf"""
(\h\cont\list.list (h h cont))
(\h.
  (\p\cont\bit0\list1.
    bit0
      (list1
        (\bit1\list2.list2
          (p
            (\exp.bit1
              (cont {ABS})
              (\list3.list3 (p (\exp2.cont {APP})))))))
      (cont list1 (list1 list1 list1)))
  (h h))
"""


def divergent_suffix_probe(term):
    omega = b.compile_lam(r"(\x.x x) (\x.x x)")
    tail_selector = b.compile_lam(r"\value\rest.rest")
    probe = ("L", ("A", ("A", b.shift(term, 1), tail_selector),
                   b.bitlist(b.enc(omega), ("V", 0))))
    assert b.normalize(b.enc(probe), 1 << 16) == "0010"


def main():
    start = time.monotonic()
    records = []
    for name, expected_bits, source in [
        ("int206_stream_handler", 206, DIRECT),
        ("int196_stream_handler", 196, SHARED),
    ]:
        term = b.compile_lam(source)
        bits = b.enc(term)
        assert len(bits) == expected_bits
        (MACHINES / f"{name}.lam").write_text(
            "-- Scott-handler recursion; generated by stream_handler.py.\n"
            "-- E C (<M> ++ N) =beta C (\\z.M) N for closed M.\n"
            + source.strip() + "\n"
        )
        (MACHINES / f"{name}.blc").write_text(bits + "\n")
        ok, skipped, failures = b.check(term, max_bits=18, threads=2)
        divergent_suffix_probe(term)
        record = {
            "name": name, "bits": len(bits),
            "battery": {"ok": ok, "skipped": skipped, "failures": failures},
            "divergent_source_suffix": True,
        }
        records.append(record)
        assert ok == 667 and skipped == 1 and not failures, record
    results = {
        "search_performed": False,
        "variants": records,
        "elapsed_seconds": round(time.monotonic() - start, 3),
    }
    (RESULTS / "stream_handler.json").write_text(
        json.dumps(results, indent=2) + "\n"
    )
    print(json.dumps(results, indent=2))


if __name__ == "__main__":
    main()
