#!/usr/bin/env python3
"""A 323-bit interpreter sharing the parser generator with APP control.

This explicit construction uses one generator for parsing and value-driven
application. Its boxes and adapters make it larger than the 165.
No candidate enumeration is used.
"""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import json
import sys
import time

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / 'tools/self-interpreter'))
import battery as b

F = r'(\e\x.x)'
BOX = r'(\value\tail\k.k g value tail)'
ABS = r'(\g\f\n\k.k g (\e\a.f (\b\r.b a (r e))) n)'
MAP = r'(\g\h\n\k.k g (\e.f e (h e)) n)'
NEXT = rf'(\bit\rest.(\v.bit (v {ABS}) (v v)) (g g rest rest {F} rest))'
READ = rf'((\next.r (\bit.bit (\unused\tail.tail next) {BOX}) (r r r)) {NEXT})'
GENERATOR = rf'(\g\u\v\f\r.{READ} {MAP})'
ADAPTER = rf'(\g\c\s.g g s s {F} s (\q\f\n.c f n))'
SOURCE = f'{ADAPTER} {GENERATOR}'


def nf(source):
    result = b.normalize(b.enc(b.compile_lam(source)), 1 << 17)
    assert result is not None, source
    return result


def divergent_suffix(interpreter, source):
    term = b.compile_lam(source)
    probe = ('L', ('A', ('A', b.shift(interpreter, 1), b.FALSE),
                   b.bitlist(b.enc(term), ('V', 0))))
    result = b.normalize(b.enc(probe), 1 << 18)
    assert result == '0010', (source, result)


def main():
    start = time.monotonic()
    term = b.compile_lam(SOURCE)
    generator = b.compile_lam(GENERATOR)
    core = generator
    for _ in range(5):
        assert core[0] == 'L'
        core = core[1]
    read, map_ = core[1:]
    reader = read[1][1]
    next_ = read[2]
    sizes = {
        'generator': len(b.enc(generator)),
        'public_adapter': len(b.enc(b.compile_lam(ADAPTER))),
        'outer_application': 2,
        'interpreter': len(b.enc(term)),
    }
    assert sizes == {'generator': 262, 'public_adapter': 59,
                     'outer_application': 2, 'interpreter': 323}, sizes
    generator_parts = {
        'five_generator_binders': 10,
        'next_let_lambda_and_application': 4,
        'whole_stream_reader_in_frame': len(b.enc(reader)),
        'next_in_frame': len(b.enc(next_)),
        'common_map_application': 2,
        'common_map_in_frame': len(b.enc(map_)),
    }
    assert sum(generator_parts.values()) == 262, generator_parts
    equations = [
        ('box_self_application_calls_parser_generator',
         r'\g\f\r.(\k.k g f r) (\k.k g f r)',
         r'\g\f\r.g g f r f r'),
        ('box_maps_abstraction',
         rf'\g\f\n.(\k.k g f n) {ABS}',
         r'\g\f\n\k.k g (\e\a.f (\b\r.b a (r e))) n'),
        ('box_maps_application_accumulator',
         rf'\f\g\h\n.(\k.k g h n) {MAP}',
         r'\f\g\h\n\k.k g (\e.f e (h e)) n'),
        ('left_seed_is_exact_on_lambda_payloads',
         rf'\a.\e.{F} e ((\z.a z) e)',
         r'\a\z.a z'),
        ('public_box_consumer',
         r'\c\g\f\n.(\k.k g f n) (\q\v\r.c v r)',
         r'\c\g\f\n.c f n'),
    ]
    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(nf, [s for _, left, right in equations
                                    for s in (left, right)]))
    for i, (name, _, _) in enumerate(equations):
        assert results[2*i] == results[2*i+1], name
    ok, skipped, failures = b.check(term, max_bits=18, threads=2)
    assert (ok, skipped, len(failures)) == (667, 1, 0), failures
    divergent = {'omega': r'(\x.x x) (\x.x x)',
                 'lambda_omega': r'\a.(\x.x x) (\x.x x)'}
    with ThreadPoolExecutor(max_workers=2) as pool:
        list(pool.map(lambda src: divergent_suffix(term, src), divergent.values()))
    report = {'search_performed': False, 'sizes': sizes,
              'generator_parts': generator_parts,
              'rigid_equations': [name for name, _, _ in equations],
              'battery': {'ok': ok, 'skipped': skipped, 'failures': failures},
              'divergent_source_suffixes': list(divergent),
              'elapsed_seconds': round(time.monotonic() - start, 3)}
    machines = ROOT / 'data/self-interpreter/machines'
    name = 'int323_shared_tag'
    (machines / f'{name}.lam').write_text(
        '-- Shared parser/APP generator; generated by shared_tag.py.\n'
        '-- 323 bits: generator sharing is possible, but this is not sub-165.\n'
        '-- E C (<M> ++ N) =beta C (lambda z.M) N for closed M.\n'
        + SOURCE + '\n')
    (machines / f'{name}.blc').write_text(b.enc(term) + '\n')
    path = ROOT / 'data/self-interpreter/theory/shared_tag.json'
    path.write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
